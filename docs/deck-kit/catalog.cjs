#!/usr/bin/env node
/* catalog.cjs — writes SECTIONS.md from visual-map.json (so the catalog can
 * never drift from the code) and audits a project for unfilled slides.
 *   node catalog.cjs            -> rewrite SECTIONS.md
 *   node catalog.cjs dealghost  -> rewrite it, then report what is still blank
 */
const fs = require('fs'), path = require('path');
const MAP = require('./visual-map.json');
const un = s => String(s).replace(/&#8212;/g, '—').replace(/&#183;/g, '·').replace(/&#8217;/g, '’').replace(/&#215;/g, '×');

/* ---------- catalog ---------- */
const rows = Object.entries(MAP.slides).map(([id, s]) =>
  `| \`${id}\` | ${s.purpose} | ${s.recipe ? '`' + s.recipe + '`' : '—'} | ${s.done} |`);

const recipes = Object.entries(MAP.recipes).map(([name, r]) =>
  `### \`${name}\`\n\n${r.use}\n\n\`\`\`js\n${r.shape}\n\`\`\`\n\nHeight: ${r.height}px equivalent.\n`);

const fallbacks = Object.entries(MAP.slides).filter(([, s]) => s.fallback)
  .map(([id, s]) => `| \`${id}\` | ${s.needs ? s.needs.join(', ') : '—'} | ${s.fallback} |`);

fs.writeFileSync(path.join(__dirname, 'SECTIONS.md'), `# Sections and visuals

Generated by \`node catalog.cjs\` from \`visual-map.json\`. Edit the JSON, not this file.

13 slides. ${Object.values(MAP.slides).filter(s => s.recipe).length} carry a generated diagram; the rest are
deliberately type-only — a visual there competes with the line you want heard.

## The slides

| Slide | What it is for | Visual | Done when |
|---|---|---|---|
${rows.join('\n')}

## The seven recipes

Every recipe emits \`div\` / \`p\` / \`x-shape\` markup styled from theme tokens, written
**into the slide file itself**. No images, no external URLs. Swapping themes recolors
every diagram with no edit to any slide.

${recipes.join('\n')}
## When the data isn't there

The build never invents a figure. A slide missing its data renders the fallback and
\`build.cjs\` prints which fired.

| Slide | Needs | Falls back to |
|---|---|---|
${fallbacks.join('\n')}

## Cannot be generated

${Object.entries(MAP.cannot_generate).map(([k, v]) => `- **${k.replace(/_/g, ' ')}** — ${v}`).join('\n')}
`);
console.log('wrote SECTIONS.md');

/* ---------- readiness audit ---------- */
const slug = process.argv[2];
if (!slug) process.exit(0);
const P = require(`./projects/${slug}.cjs`);

const blanks = [];
(function walk(node, trail) {
  if (typeof node === 'string') {
    if (/^\s*&#8212;\s*$/.test(node)) blanks.push([trail, 'em dash placeholder']);
    else if (/\[[^\]]{4,}\]/.test(node)) blanks.push([trail, 'bracketed: ' + un(node).trim()]);
  } else if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) walk(v, trail ? `${trail}.${k}` : k);
  }
})(P, '');

const report = Object.keys(MAP.slides).map(id => {
  const s = P[id] || {};
  const mine = blanks.filter(([tr]) => tr.startsWith(id + '.'));
  const unverified = s.verified === false;
  const state = mine.length || unverified ? 'BLOCKED' : 'ready';
  const why = [...new Set(mine.map(([, w]) => w.split(':')[0]))].concat(unverified ? ['marked unverified'] : []);
  return [id, state, why.join(', ')];
});

const w = Math.max(...report.map(r => r[0].length));
console.log(`\n${slug} — deck readiness\n`);
for (const [id, state, why] of report)
  console.log(`  ${id.padEnd(w)}  ${state.padEnd(8)}  ${why}`);
const bad = report.filter(r => r[1] === 'BLOCKED');
console.log(`\n  ${report.length - bad.length}/${report.length} ready.` +
  (bad.length ? `  Fill before presenting: ${bad.map(r => r[0]).join(', ')}` : ''));
